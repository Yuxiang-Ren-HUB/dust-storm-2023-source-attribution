def load_regions3(mg_buffer_km=0.0):
    """返回 {name: 布尔掩膜}, 由 source_region_mask.npy 现算, 避免与画图脚本不一致。
    mg_buffer_km>0 时对MG做形态学膨胀(向外扩buffer_km), 用于测试"MG源区偏小,
    衰减尾总量解释不足"这个假说是否能靠扩大释放面积改善——只放大掩膜范围,
    实际释放量仍由 emit_spacetime 的起沙检测格点决定, 不会凭空捏造质量,
    只是让原本被掩膜边界排除、但确有起沙信号的邻近像元也能被纳入。
    """
    import numpy as np
    from pathlib import Path
    from scipy.ndimage import label, binary_dilation
    rr = Path(r"F:\研\科研\Python") / "atmosphere_revision_figs" / "reviewer_response"
    nx, ny = 1400, 700
    lon, _ = np.meshgrid(np.linspace(70, 126, nx), np.linspace(52, 30, ny))
    m = np.load(rr / "source_region_mask.npy")
    lb, n = label(m)
    comps = sorted(range(1, n + 1), key=lambda i: lon[lb == i].mean())
    tk, mg = lb == comps[0], lb == comps[1]
    if mg_buffer_km > 0:
        dx_km = 56.0 * 111.32 / nx     # ~4.45 km/格
        dy_km = 22.0 * 111.32 / ny     # ~3.50 km/格
        iters = max(1, round(mg_buffer_km / ((dx_km + dy_km) / 2.0)))
        mg = binary_dilation(mg, iterations=iters) & ~tk   # 不侵入TK区
    return {"TK1": tk & (lon < TK_SPLIT_LON),
            "TK2": tk & (lon >= TK_SPLIT_LON),
            "MG": mg}

